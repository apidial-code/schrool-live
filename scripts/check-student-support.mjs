import assert from "node:assert/strict";
import fs from "node:fs";
import ts from "typescript";
const source = fs.readFileSync(new URL("../shared/standardSupport.ts", import.meta.url),"utf8");
const code = ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText;
const {validDate,sydneyDate,supportWindow:w} = await import(`data:text/javascript;base64,${Buffer.from(code).toString("base64")}`);
assert.equal(validDate("2026-02-30"),false);
assert.equal(validDate("2028-02-29"),true);
assert.equal(sydneyDate("2026-11-19T13:30:00Z"),"2026-11-20");
const activation="2026-11-19T11:01:25Z";
assert.equal(w(activation,"2026-11-19","2026-11-20").week,1);
assert.equal(w(activation,"2026-11-25","2026-11-25").week,1);
assert.equal(w(activation,"2026-11-26","2026-11-26").week,2);
assert.equal(w(activation,"2026-11-18","2026-11-20").eligible,false);
assert.equal(w(activation,"2026-11-21","2026-11-20").eligible,false);
assert.equal(w(activation,"2027-02-19","2027-02-19").eligible,false);
assert.equal(w("2026-01-31T01:00:00Z","2026-04-29","2026-04-29").end,"2026-04-30");
assert.equal(w("2026-09-30T01:00:00Z","2026-10-07","2026-10-07").week,2);
assert.equal(w(null,"2026-11-20","2026-11-20"),null);
console.log("Student support date and weekly-boundary checks passed.");
