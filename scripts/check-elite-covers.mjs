import assert from "node:assert/strict";
import {readFile} from "node:fs/promises";
import ts from "typescript";
const source=await readFile(new URL("../shared/eliteCover.ts",import.meta.url),"utf8");
const js=ts.transpileModule(source,{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.ES2022}}).outputText;
const {coverReviewSnapshot,coverNeedsReturn}=await import("data:text/javascript;base64,"+Buffer.from(js).toString("base64"));
const session={id:10,lessonId:3,startsAt:new Date("2026-11-23T07:00:00Z"),endsAt:new Date("2026-11-23T08:00:00Z")};
const cover={id:1,handover:"Continue equivalent fractions with visual diagrams."};
const prior=[{id:5,sessionId:8},{id:7,sessionId:9}],key=coverReviewSnapshot(session,cover,prior);
assert.equal(key,coverReviewSnapshot(session,cover,[...prior].reverse()));
assert.equal(key,coverReviewSnapshot(session,cover,[...prior,{id:11,sessionId:10}]));
assert.notEqual(key,coverReviewSnapshot(session,cover,[...prior,{id:12,sessionId:9}]));
assert.notEqual(key,coverReviewSnapshot({...session,lessonId:4},cover,prior));
assert.notEqual(key,coverReviewSnapshot({...session,startsAt:new Date("2026-11-23T08:00:00Z")},cover,prior));
assert.notEqual(key,coverReviewSnapshot(session,{...cover,handover:"Updated teaching objectives."},prior));
assert(coverNeedsReturn({status:"delivered",returnedReportId:null},11));
assert(!coverNeedsReturn({status:"returned",returnedReportId:11},11));
assert(coverNeedsReturn({status:"returned",returnedReportId:11},12));
assert(coverNeedsReturn({status:"returned",returnedReportId:11},undefined));
console.log("Cover review snapshots, changed lesson/report detection, own-report corrections and regular tutor return-review checks passed.");
